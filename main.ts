scene.onHitWall(SpriteKind.Enemy, function (sprite, location) {
    if (characterAnimations.matchesRule(sprite, characterAnimations.rule(Predicate.HittingWallLeft)) || characterAnimations.matchesRule(sprite, characterAnimations.rule(Predicate.HittingWallRight))) {
        sprite.vx = sprites.readDataNumber(sprite, "Speed") * -1
        sprite.sayText(sprites.readDataNumber(sprite, "Speed") * -1)
    } else {
        if (sprite.vx != 0) {
            sprites.setDataNumber(sprite, "Speed", sprite.vx)
        }
    }
    if (sight.isInSightCone(
    sprite,
    mySprite,
    0,
    0,
    0
    )) {
        sprite.vx = 0
    }
})
